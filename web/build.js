#!/usr/bin/env node
// Assembles a self-contained browser build of the questboard in web/out/.
// Usage: node web/build.js [--base-url <sync url>] [--token <token or "proxy">] [--out <dir>]
// With no --base-url the page falls back to a same-origin "./api" proxy (see web/README.md).
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const opt = (name, dflt) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : dflt; };
const out = path.resolve(opt('--out', path.join(__dirname, 'out')));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'fonts'), { recursive: true });

const renderer = path.join(root, 'src', 'renderer');
for (const f of fs.readdirSync(renderer)) {
  let text = fs.readFileSync(path.join(renderer, f), 'utf8');
  if (f === 'fonts.css') text = text.split('../../assets/fonts/').join('fonts/');
  if (f === 'styles.css' || f === 'sound.js') text = text.split('../../assets/').join('');
  if (f === 'index.html') {
    text = text
      .replace('<link rel="stylesheet" href="styles.css" />', '<link rel="stylesheet" href="styles.css" />\n  <link rel="stylesheet" href="web.css" />')
      .replace('<script src="merge.js"></script>', '<script src="config.js"></script>\n  <script src="shim.js"></script>\n  <script src="merge.js"></script>')
      .replace('<meta charset="utf-8" />', '<meta charset="utf-8" />\n  <meta name="viewport" content="width=device-width, initial-scale=1" />');
    if (!text.includes('shim.js')) throw new Error('index.html: could not insert the browser shim');
  }
  fs.writeFileSync(path.join(out, f), text);
}
for (const f of fs.readdirSync(path.join(root, 'assets', 'fonts'))) fs.copyFileSync(path.join(root, 'assets', 'fonts', f), path.join(out, 'fonts', f));
fs.copyFileSync(path.join(root, 'assets', 'wood.png'), path.join(out, 'wood.png'));
fs.mkdirSync(path.join(out, 'sfx', 'cut'), { recursive: true });
for (const f of fs.readdirSync(path.join(root, 'assets', 'sfx', 'cut'))) fs.copyFileSync(path.join(root, 'assets', 'sfx', 'cut', f), path.join(out, 'sfx', 'cut', f));
for (const f of ['shim.js', 'web.css']) fs.copyFileSync(path.join(__dirname, f), path.join(out, f));

const baseUrl = opt('--base-url', '');
const token = opt('--token', '');
const config = `// Generated by web/build.js. baseUrl '' means "./api" next to this page (a proxy that adds the token).
window.QB_WEB = {
  baseUrl: ${JSON.stringify(baseUrl)} || new URL('./api', location.href).href.replace(/\\/$/, ''),
  token: ${JSON.stringify(token)} || 'proxy',
  version: ${JSON.stringify(pkg.version + '-web')},
  device: 'web',
};
`;
fs.writeFileSync(path.join(out, 'config.js'), config);
console.log(`web build written to ${out}`);
